/* ========== 工具函数 ========== */

/* 生成格式化学号: 2024 + 6 位零填充序号 */
void makeStudentId(int seq, char *buf)
{
    sprintf(buf, "2024%06d", seq);
}

/* ========== 主函数 ========== */
int main(void)
{
    int n;
    printf("╔══════════════════════════════════════╗\n");
    printf("║   大规模测试数据生成器               ║\n");
    printf("║   生成选课记录 CSV (D:\\file.csv)    ║\n");
    printf("╚══════════════════════════════════════╝\n\n");
    printf("请输入要生成的测试数据条数 (1 ~ %d): ", MAX_RECORDS);
    fflush(stdout);

    if (scanf("%d", &n) != 1 || n <= 0 || n > MAX_RECORDS)
    {
        printf("输入无效！请输入 1 ~ %d 之间的整数。\n", MAX_RECORDS);
        return 1;
    }

    printf("\n正在生成 %d 条测试数据...\n", n);

    /* 初始化随机种子 */
    srand((unsigned int)time(NULL));

    /* 分配去重位图: used[stuIdx * NUM_COURSES + courseIdx] = 1 表示已选 */
    /* 每个学生最多选 MAX_COURSES_STU 门课，最多需要 MAX_STUDENTS 个学生 */
    int maxStudentsNeeded = (n / 3) + 1; /* 每人至少3门课 */
    if (maxStudentsNeeded > MAX_STUDENTS)
        maxStudentsNeeded = MAX_STUDENTS;
    int bitmapSize = maxStudentsNeeded * NUM_COURSES;
    unsigned char *used = (unsigned char *)calloc(bitmapSize, sizeof(unsigned char));
    if (!used)
    {
        printf("内存分配失败！\n");
        return 1;
    }

    /* 打开输出文件 */
    FILE *fp = fopen("D:\\file.csv", "w");
    if (!fp)
    {
        printf("无法创建文件 D:\\file.csv，请检查路径是否可写。\n");
        free(used);
        return 1;
    }

    /* 写 CSV 表头 */
    fprintf(fp, "studentId,name,college,courseId,courseName,credit,semester,selectDate,score\n");

    int generated = 0;
    int studentSeq = 1; /* 学号后缀从 1 开始 */

    while (generated < n && studentSeq <= maxStudentsNeeded)
    {
        int stuIdx = studentSeq - 1; /* 位图中的学生索引 */

        /* 该学生选修 3~10 门课 */
        int coursesThisStudent = (rand() % 8) + 3;
        int remaining = n - generated;
        if (coursesThisStudent > remaining)
            coursesThisStudent = remaining;

        /* 为学生随机挑选互不重复的课程 */
        int *picked = (int *)malloc(coursesThisStudent * sizeof(int));
        if (!picked)
        {
            break;
        }

        int pickedCount = 0;
        int safety = 0;
        while (pickedCount < coursesThisStudent && safety < (int)(NUM_COURSES * 2))
        {
            int c = rand() % NUM_COURSES;
            if (!used[stuIdx * NUM_COURSES + c])
            {
                used[stuIdx * NUM_COURSES + c] = 1;
                picked[pickedCount++] = c;
            }
            safety++;
        }

        /* 为学生确定姓名、学院 */
        char studentId[13];
        makeStudentId(studentSeq, studentId);
        const char *studentName = namePool[rand() % NUM_NAMES];
        const char *studentCollege = collegePool[rand() % NUM_COLLEGES];
        int studentSemesterOffset = rand() % NUM_SEMESTERS; /* 学生入学对应学期偏移 */

        /* 为每门选课生成记录 */
        for (int j = 0; j < pickedCount && generated < n; j++)
        {
            int cIdx = picked[j];
            CourseDef *course = &coursePool[cIdx];

            /* 学期: 在入学学期基础上往后偏移 0~3 */
            int semIdx = (studentSemesterOffset + (rand() % 4));
            if (semIdx >= (int)NUM_SEMESTERS)
                semIdx = (int)NUM_SEMESTERS - 1;
            const char *sem = semesterPool[semIdx];

            /* 选课日期: 根据学期生成合理日期 */
            char date[11];
            {
                int year, month;
                sscanf(sem, "%d-%d", &year, &month);
                /* 第一学期约9月，第二学期约2月 */
                int m = (month == 1) ? 9 : 2;
                int d = (rand() % 28) + 1;
                sprintf(date, "%04d-%02d-%02d", year, m, d);
            }

            /* 成绩: 正态分布倾向 (均值70，标准差15) */
            int score;
            {
                /* 用简单的 Box-Muller 近似: 叠加多个均匀分布 */
                int sum = 0;
                for (int k = 0; k < 6; k++)
                    sum += rand() % 21; /* 0~20 × 6 = 0~120 */
                score = 40 + sum / 3;   /* 40~80 范围 */
                if (score < 0)
                    score = 0;
                if (score > 100)
                    score = 100;
                /* 随机浮动 */
                score += (rand() % 21) - 10;
                if (score < 0)
                    score = rand() % 40;
                if (score > 100)
                    score = 85 + rand() % 16;
            }

            fprintf(fp, "%s,%s,%s,%s,%s,%.1f,%s,%s,%d\n",
                    studentId, studentName, studentCollege,
                    course->id, course->name, course->credit,
                    sem, date, score);

            generated++;
        }

        free(picked);
        studentSeq++;

        /* 进度提示（每1万条打印一次） */
        if (generated % 10000 == 0)
        {
            printf("  已生成 %d / %d 条 (%.1f%%)\n",
                   generated, n, 100.0 * generated / n);
        }
    }

    fclose(fp);
    free(used);

    printf("\n✅ 完成！共生成 %d 条测试数据，已保存至:\n", generated);
    printf("   D:\\file.csv\n");
    printf("\n文件大小约 %.1f MB，可直接供 哈希表.c 和 双向链表.c 加载测试。\n",
           generated * 0.15 / 1024.0);

    return 0;
}
